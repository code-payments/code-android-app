package com.flipcash.chat

import com.codeinc.flipcash.wire.messaging.v1.Content
import com.squareup.wire.Message
import com.squareup.wire.ProtoAdapter
import com.squareup.wire.WireField
import java.io.File
import java.util.zip.ZipFile
import kotlin.test.Test
import kotlin.test.assertEquals

private const val CONTENT = "flipcash.messaging.v1.Content"

/**
 * Rebuilds [ContentCanonicalSchema] from the `@WireField` annotations of every message
 * `messaging.v1.Content` reaches in the flipcash2 Wire artifact, and fails if the checked-in file
 * differs. Run with UPDATE_CANONICAL_SCHEMA=1 to rewrite it.
 *
 * The reader is a trimmed copy of `:services:flipcash-client`'s `WireSchemaReader` (a jvmTest
 * class, so it cannot be shared). It prints the reachable types whose Wire `encode()` order differs
 * from field-number order.
 */
class ContentCanonicalSchemaTest {

    @Test
    fun schemaMatchesWireArtifact() {
        val types = ContentSchemaReader.read(Content::class.java, "com/codeinc/flipcash/wire/")
        val reachable = ContentSchemaReader.reachable(types, CONTENT)
        assertEquals(emptySet(), reachable.filter { it !in types }.toSet(), "Content reaches types outside the artifact")
        val schema = reachable.map(types::getValue)
        // protobuf-java writes map entries in insertion order, the canonical encoder sorts them, so a
        // map field reachable from Content would seal different bytes from Android.
        assertEquals(emptyList(), schema.filter { type -> type.fields.any { it.kind.startsWith("Map(") } }.map { it.name }, "Content reaches a map field")
        val source = ContentSchemaReader.render(schema)
        val file = File(checkNotNull(System.getProperty("canonicalSchemaFile")))
        if (System.getenv("UPDATE_CANONICAL_SCHEMA") == "1") file.writeText(source)
        assertEquals(source, file.readText(), "ContentCanonicalSchema.kt is stale; re-run with UPDATE_CANONICAL_SCHEMA=1")
        println("canonical-order Content types where Wire differs: ${schema.filter(ContentSchemaReader::wireOrderDiffers).map { it.name }.sorted()}")
    }
}

private object ContentSchemaReader {
    class Field(val tag: Int, val kind: String, val oneof: Boolean, val schemaIndex: Int)
    class Type(val name: String, val fields: List<Field>)

    /** Wire writes regular fields in declaration order, then oneof members in declaration order. */
    fun wireOrderDiffers(type: Type): Boolean {
        val emitted = type.fields.sortedWith(compareBy({ it.oneof }, { it.schemaIndex })).map { it.tag }
        return emitted != emitted.sorted()
    }

    fun reachable(types: Map<String, Type>, root: String): Set<String> {
        val seen = linkedSetOf<String>()
        fun visit(name: String) {
            if (!seen.add(name)) return
            types[name]?.fields?.forEach { field -> messageType(field.kind)?.let(::visit) }
        }
        visit(root)
        return seen
    }

    fun render(types: List<Type>): String = buildString {
        appendLine("// Generated by ContentCanonicalSchemaTest from com.flipcash:flipcash2-client-protocol-wire. Do not edit; run")
        appendLine("// UPDATE_CANONICAL_SCHEMA=1 ./gradlew :services:flipcash-chat:jvmTest to refresh.")
        appendLine("package com.flipcash.chat")
        appendLine()
        appendLine("import com.getcode.wire.canonical.CanonicalField")
        appendLine("import com.getcode.wire.canonical.CanonicalSchema")
        if (types.any { type -> type.fields.any { it.kind.startsWith("Map(") } }) appendLine("import com.getcode.wire.canonical.MapKey")
        appendLine()
        appendLine("private val S = CanonicalField.Scalar")
        appendLine("private fun M(type: String) = CanonicalField.Message(type)")
        if (types.any { type -> type.fields.any { it.kind.startsWith("Map(") } }) {
            appendLine("private fun Map(key: MapKey, value: String?) = CanonicalField.MapOf(key, value)")
        }
        appendLine()
        appendLine("/** Every message `$CONTENT` reaches, for writing it in field-number order. */")
        appendLine("internal val ContentCanonicalSchema: CanonicalSchema = CanonicalSchema(")
        appendLine("    mapOf(")
        types.sortedBy { it.name }.forEach { type ->
            val fields = type.fields.sortedBy { it.tag }.joinToString(", ") { "${it.tag} to ${it.kind}" }
            appendLine("        \"${type.name}\" to mapOf($fields),")
        }
        appendLine("    ),")
        appendLine(")")
    }

    private fun messageType(kind: String): String? =
        Regex("""M\("([^"]+)"\)""").find(kind)?.groupValues?.get(1)
            ?: Regex("""Map\(MapKey\.\w+, "([^"]+)"\)""").find(kind)?.groupValues?.get(1)

    fun read(anchor: Class<*>, prefix: String): Map<String, Type> {
        val jar = File(anchor.protectionDomain.codeSource.location.toURI())
        val classes = ZipFile(jar).use { zip ->
            zip.entries().asSequence().map { it.name }
                .filter { it.startsWith(prefix) && it.endsWith(".class") }
                .map { Class.forName(it.removeSuffix(".class").replace('/', '.'), false, anchor.classLoader) }
                .filter { Message::class.java.isAssignableFrom(it) && !java.lang.reflect.Modifier.isAbstract(it.modifiers) }
                .toList()
        }
        val types = classes.map { cls ->
            val fields = cls.declaredFields.mapNotNull { f ->
                val wire = f.getAnnotation(WireField::class.java) ?: return@mapNotNull null
                Field(wire.tag, kindOf(wire, anchor.classLoader), wire.oneofName.isNotEmpty(), wire.schemaIndex)
            }
            Type(protoName(cls), fields)
        } + wellKnown
        return types.associateBy { it.name }
    }

    private fun protoName(cls: Class<*>): String {
        val adapter = cls.getField("ADAPTER").get(null) as ProtoAdapter<*>
        return checkNotNull(adapter.typeUrl).substringAfterLast('/')
    }

    private fun kindOf(wire: WireField, loader: ClassLoader): String {
        if (wire.keyAdapter.isNotEmpty()) {
            val key = when (wire.keyAdapter.substringAfter('#')) {
                "STRING", "BYTES" -> "Bytes"
                "BOOL" -> "Bool"
                "INT32", "INT64", "SFIXED32", "SFIXED64" -> "Signed"
                "SINT32", "SINT64" -> "ZigZag"
                "UINT32", "UINT64", "FIXED32", "FIXED64" -> "Unsigned"
                else -> error("Unsupported map key ${wire.keyAdapter}")
            }
            val value = messageName(wire.adapter, loader)
            return "Map(MapKey.$key, ${value?.let { "\"$it\"" } ?: "null"})"
        }
        return messageName(wire.adapter, loader)?.let { "M(\"$it\")" } ?: "S"
    }

    /** The proto name if [adapter] encodes a message, or null for scalars and enums. */
    private fun messageName(adapter: String, loader: ClassLoader): String? {
        val (owner, member) = adapter.split('#')
        if (owner == "com.squareup.wire.ProtoAdapter") {
            return builtins[member] ?: if (member in scalars) null else error("Unsupported built-in adapter $adapter")
        }
        val cls = Class.forName(owner, false, loader)
        return if (Message::class.java.isAssignableFrom(cls)) protoName(cls) else null
    }

    private val scalars = setOf(
        "BOOL", "INT32", "UINT32", "SINT32", "FIXED32", "SFIXED32", "INT64", "UINT64", "SINT64",
        "FIXED64", "SFIXED64", "FLOAT", "DOUBLE", "STRING", "BYTES",
    )
    private val builtins = mapOf("INSTANT" to "google.protobuf.Timestamp", "DURATION" to "google.protobuf.Duration")
    private val wellKnown = listOf(
        Type("google.protobuf.Timestamp", listOf(Field(1, "S", false, 0), Field(2, "S", false, 1))),
        Type("google.protobuf.Duration", listOf(Field(1, "S", false, 0), Field(2, "S", false, 1))),
    )
}
