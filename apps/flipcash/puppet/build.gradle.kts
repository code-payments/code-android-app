val puppetJvmArgs = listOf("-Dopencode.processLifecycle.autoStart=false")

// ChatsBehaviorTest replays these. `-Ppuppet.behaviors=<dir or file>` points it at others, such as
// one file an agent is writing; the default is the synced copy of the orchestrator's behaviors.
tasks.named<Test>("test") {
    // The same heap the KMP convention gives jvm tests; the default is too small for these.
    maxHeapSize = "2g"
    jvmArgs(puppetJvmArgs)
    val behaviors = providers.gradleProperty("puppet.behaviors")
        .map { rootProject.file(it) }
        .orElse(rootProject.layout.projectDirectory.dir("test-vectors/behaviors/chats").asFile)
    inputs.files(behaviors).withPropertyName("puppetBehaviors").optional()
    systemProperty("puppet.behaviors", behaviors.get().absolutePath)
}

// The host as a process, for the orchestrator's `puppet` CLI (`ls`/`do` sessions and
// `puppet test android`). A script over the built classpath rather than a copied lib/ folder:
// several modules build a jar with the same name (core-jvm.jar), so copies would collide. Gradle
// startup stays out of a session, and so does build output on its stdout. Rerun it after a code
// change; `puppet` does that for you.
tasks.register("puppetLauncher") {
    group = "puppet"
    description = "Writes build/puppet/host, which runs the app's Puppet host on stdin/stdout."
    val runtime = sourceSets["main"].runtimeClasspath
    dependsOn(runtime)
    val java = javaToolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(21)) }
        .map { it.executablePath.asFile.absolutePath }
    val script = layout.buildDirectory.file("puppet/host")
    val classpath = provider { runtime.asPath }
    val args = puppetJvmArgs.joinToString(" ")
    inputs.files(runtime).withPropertyName("runtime")
    outputs.file(script)
    doLast {
        val file = script.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |#!/bin/sh
            |# Generated by :apps:flipcash:puppet:puppetLauncher. Rerun it after a code change.
            |exec "${java.get()}" $args -cp '${classpath.get()}' com.flipcash.app.puppet.PuppetMainKt "${'$'}@"
            |""".trimMargin(),
        )
        file.setExecutable(true)
    }
}
