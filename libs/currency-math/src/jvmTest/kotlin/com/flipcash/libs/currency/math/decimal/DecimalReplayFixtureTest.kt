package com.flipcash.libs.currency.math.decimal

import java.io.File
import java.math.BigInteger
import kotlin.random.Random
import kotlin.test.Test
import kotlin.test.assertEquals
import java.math.BigDecimal as JBigDecimal

/**
 * Regenerates `decimal_replay.txt` from `java.math` with a fixed seed and fails if the committed
 * file differs. Set `REGEN_DECIMAL_REPLAY=1` to rewrite it.
 */
class DecimalReplayFixtureTest {
    private val random = Random(0xdec1)
    private val modes = RoundingMode.entries.map { it.name }.filter { it != "UNNECESSARY" }
    private val allModes = RoundingMode.entries.map { it.name }

    private fun decimal(): String {
        if (random.nextInt(12) == 0) return listOf("0", "0E-${random.nextInt(20)}", "0E+3", "1", "-1", "10").random(random)
        val digits = when (random.nextInt(10)) {
            0 -> 1
            1 -> random.nextInt(1, 4)
            2 -> random.nextInt(18, 21) // around Long's range
            else -> random.nextInt(1, 70)
        }
        val unscaled = buildString {
            if (random.nextInt(3) == 0) append('-')
            repeat(digits) { append(random.nextInt(10)) }
        }
        val scale = when (random.nextInt(8)) {
            0 -> 0
            1 -> -random.nextInt(1, 12)
            else -> random.nextInt(0, 60)
        }
        return JBigDecimal(BigInteger(unscaled), scale).toString()
    }

    private fun precision() = (if (random.nextInt(3) == 0) 50 else random.nextInt(1, 80)).toString()
    private fun mode() = modes.random(random)
    private fun doubleBits(): String {
        val value = when (random.nextInt(4)) {
            0 -> random.nextDouble(-1e6, 1e6)
            1 -> random.nextDouble() * 10.0.pow(random.nextInt(-12, 22))
            2 -> random.nextLong(-1_000_000, 1_000_000) / 100.0
            else -> Double.fromBits(random.nextLong())
        }
        return value.toRawBits().toULong().toString(16)
    }

    private fun Double.pow(n: Int) = Math.pow(this, n.toDouble())

    private fun cases(): List<Pair<String, List<String>>> = buildList {
        repeat(300) { add("parse" to listOf(decimal())) }
        repeat(300) {
            add("add" to listOf(decimal(), decimal()))
            add("sub" to listOf(decimal(), decimal()))
            add("mul" to listOf(decimal(), decimal()))
        }
        repeat(400) {
            add("addMc" to listOf(decimal(), decimal(), precision(), mode()))
            add("subMc" to listOf(decimal(), decimal(), precision(), mode()))
            add("mulMc" to listOf(decimal(), decimal(), precision(), mode()))
            add("divMc" to listOf(decimal(), decimal(), precision(), mode()))
        }
        repeat(150) { add("negMc" to listOf(decimal(), precision(), mode())) }
        repeat(150) { add("pow" to listOf(decimal().take(12), random.nextInt(0, 12).toString())) }
        repeat(150) { add("powMc" to listOf(decimal(), random.nextInt(-8, 30).toString(), precision(), mode())) }
        repeat(400) { add("setScale" to listOf(decimal(), random.nextInt(-5, 40).toString(), allModes.random(random))) }
        repeat(150) { add("movePointLeft" to listOf(decimal(), random.nextInt(-20, 20).toString())) }
        repeat(200) {
            val a = decimal()
            add("cmp" to listOf(a, if (random.nextBoolean()) a else decimal()))
            add("eq" to listOf(a, if (random.nextBoolean()) JBigDecimal(a).setScale(JBigDecimal(a).scale() + 1).toString() else a))
        }
        repeat(150) {
            add("longExact" to listOf(decimal()))
            add("toLong" to listOf(decimal()))
            add("toInt" to listOf(decimal()))
            add("toDouble" to listOf(decimal()))
        }
        repeat(200) { add("fromDoubleMc" to listOf(doubleBits(), precision(), mode())) }
        repeat(200) { add("valueOfDouble" to listOf(doubleBits())) }
        repeat(100) { add("fromLongMc" to listOf(random.nextLong().toString(), precision(), mode())) }
    }

    private fun render(): String = buildString {
        append("# Generated by DecimalReplayFixtureTest from java.math; do not edit.\n")
        for ((op, args) in cases()) {
            append(op).append('|').append(args.joinToString("|")).append('|').append(DecimalReplay.evaluate(op, args)).append('\n')
        }
    }

    @Test
    fun fixtureMatchesJavaMath() {
        val file = File("src/androidDeviceTest/assets/${DecimalReplay.FILE}")
        val expected = render()
        if (System.getenv("REGEN_DECIMAL_REPLAY") == "1") file.writeText(expected)
        assertEquals(expected, file.readText(), "decimal_replay.txt is stale; rerun with REGEN_DECIMAL_REPLAY=1")
    }
}
