#!/usr/bin/env python3
"""Generates src/commonTest/resources/group_cipher.json from libsodium directly (ctypes), independent of
DefaultChatCipher. Usage: python3 scripts/gen_group_cipher.py [path/to/libsodium.dylib]"""
import ctypes, ctypes.util, hashlib, hmac, json, os, sys

lib = ctypes.CDLL(sys.argv[1] if len(sys.argv) > 1 else (ctypes.util.find_library("sodium") or "/opt/homebrew/lib/libsodium.dylib"))
assert lib.sodium_init() >= 0
ull = ctypes.c_ulonglong

def buf(n): return ctypes.create_string_buffer(n)

def seal(key, nonce, plain, aad):
    out = buf(len(plain) + 16); n = ull()
    assert lib.crypto_aead_xchacha20poly1305_ietf_encrypt(out, ctypes.byref(n), plain, ull(len(plain)), aad, ull(len(aad)), None, nonce, key) == 0
    return out.raw[: n.value]

def keypair(seed):
    pk, sk = buf(32), buf(64)
    assert lib.crypto_sign_seed_keypair(pk, sk, seed) == 0
    return pk.raw, sk.raw

def x_priv(sk):
    o = buf(32); assert lib.crypto_sign_ed25519_sk_to_curve25519(o, sk) == 0; return o.raw

def x_pub(pk):
    o = buf(32); assert lib.crypto_sign_ed25519_pk_to_curve25519(o, pk) == 0; return o.raw

def x25519(priv, pub):
    o = buf(32); assert lib.crypto_scalarmult(o, priv, pub) == 0; return o.raw

def hkdf(ikm, salt, info, length=32):
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    t, out, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest(); out += t; i += 1
    return out[:length]

GROUP = b"flipcash-group-e2ee-v1"
GROUP_BLOB = b"flipcash-group-e2ee-blob-v1"
WRAP = b"flipcash-group-key-wrap-v1"
h = lambda b: b.hex()
alice_seed = bytes(range(1, 33)); bob_seed = bytes(range(0x65, 0x85))
alice_pk, alice_sk = keypair(alice_seed); bob_pk, bob_sk = keypair(bob_seed)
chat_id = bytes.fromhex("97dfb79f2c2c44a9bd581b3b4fd30e7aee470d3b53062288886a976dd8ade15e")
group_key = bytes(range(0xa0, 0xc0))
nonce = bytes(range(0x78, 0x90))
sender16 = bytes.fromhex("0f1e2d3c4b5a69788796a5b4c3d2e1f0")
sender32 = bytes(range(0x40, 0x60))

messages = []
for name, content, sender in [
    ("empty", b"", sender16),
    ("text", bytes.fromhex("0a070a0568656c6c6f"), sender16),
    ("longer-sender-id", bytes(range(256)), sender32),
    ("one-byte-sender-id", b"hi", b"\x07"),
]:
    aad = GROUP + chat_id + sender
    messages.append({"name": name, "groupKey": h(group_key), "chatId": h(chat_id), "senderId": h(sender),
                     "content": h(content), "nonce": h(nonce), "aad": h(aad), "ciphertext": h(seal(group_key, nonce, content, aad))})

blob_id = bytes.fromhex("a0a1a2a3a4a5a6a7a8a9aaabacadaeaf")
blobs = []
for name, image in [("empty", b""), ("image", bytes(range(200)))]:
    aad = GROUP_BLOB + chat_id + blob_id + sender16
    blobs.append({"name": name, "groupKey": h(group_key), "chatId": h(chat_id), "blobId": h(blob_id), "senderId": h(sender16),
                  "image": h(image), "nonce": h(nonce), "aad": h(aad), "blob": h(nonce + seal(group_key, nonce, image, aad))})

def wrap(w_pk, w_sk, r_pk):
    ss = x25519(x_priv(w_sk), x_pub(r_pk))
    salt = min(w_pk, r_pk) + max(w_pk, r_pk)
    k = hkdf(ss, salt, WRAP + chat_id)
    aad = WRAP + chat_id + w_pk + r_pk
    return k, aad, seal(k, nonce, group_key, aad)

wraps = []
for name, (w_seed, w_pk, w_sk), r_pk in [
    ("creator-for-member", (alice_seed, alice_pk, alice_sk), bob_pk),
    ("self", (alice_seed, alice_pk, alice_sk), alice_pk),
]:
    k, aad, ct = wrap(w_pk, w_sk, r_pk)
    wraps.append({"name": name, "wrapperSeed": h(w_seed), "wrapperPublicKey": h(w_pk), "recipientPublicKey": h(r_pk),
                  "recipientSeed": h(bob_seed if r_pk == bob_pk else alice_seed), "chatId": h(chat_id),
                  "groupKey": h(group_key), "wrappingKey": h(k), "nonce": h(nonce), "aad": h(aad), "ciphertext": h(ct)})

m = messages[1]; ct = bytes.fromhex(m["ciphertext"])
rejects = [
    dict(m, name="wrong-sender-id", senderId=h(sender32)),
    dict(m, name="wrong-chat-id", chatId=h(bytes(32))),
    dict(m, name="tampered", ciphertext=h(bytes([ct[0] ^ 1]) + ct[1:])),
    dict(m, name="dm-label", ciphertext=h(seal(group_key, nonce, bytes.fromhex(m["content"]), b"flipcash-dm-e2ee-v1" + chat_id + sender16))),
    dict(m, name="blob-as-message", ciphertext=h(seal(group_key, nonce, bytes.fromhex(m["content"]), GROUP_BLOB + chat_id + blob_id + sender16))),
]
for r in rejects: r.pop("aad", None)

out = {
    "algorithm": "flipcash-group-e2ee-v1 / CHAT_KEY_XCHACHA20POLY1305, flipcash-group-key-wrap-v1",
    "spec": "EncryptedContent (messaging/v1/model.proto) and KeyEnvelope (chat/v1/model.proto) in flipcash2-protobuf-api. "
            "aad = 'flipcash-group-e2ee-v1' || chatId || senderId; blob aad = 'flipcash-group-e2ee-blob-v1' || chatId || blobId || senderId; "
            "senderId is the raw UserId.value bytes. Generated by scripts/gen_group_cipher.py against libsodium, not DefaultChatCipher.",
    "messages": messages, "blobs": blobs, "wraps": wraps, "rejects": {"decryptGroup": rejects},
}
dst = os.path.join(os.path.dirname(__file__), "..", "src", "commonTest", "resources", "group_cipher.json")
open(dst, "w").write(json.dumps(out, indent=2) + "\n")
print("wrote", os.path.normpath(dst))
